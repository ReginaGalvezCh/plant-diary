export function preferredLanguage(saved, browserLanguages) {
  if (Object.hasOwn(languages, saved)) return saved;
  return browserLanguages.map(tag => tag.toLowerCase().split("-")[0])
    .find(code => Object.hasOwn(languages, code)) ?? "en";
}
